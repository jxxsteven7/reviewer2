#!/usr/bin/env node
// Builds shared/src/han-variants.ts: the table that turns traditional Chinese characters into
// simplified ones, so that the clue check sees a word and its traditional spelling as the same
// word (shared/src/games/keywords/clue.ts).
//
// The table comes from TSCharacters.txt, the character table of the Open Chinese Convert
// project (OpenCC). It holds every character of the basic CJK block, U+4E00 to U+9FFF, that
// OpenCC turns into another character of that block. Where OpenCC lists several simplified
// forms, the first one counts, as in OpenCC itself, and a form that has a simpler form of its
// own is followed to the end. The characters are written as \u escapes, like all Chinese text
// in the code (docs/rules/language.md).
//
// Usage:
//   node scripts/build-han-variants.mjs path/to/TSCharacters.txt <version>
//
// TSCharacters.txt is data/dictionary/TSCharacters.txt in https://github.com/BYVoid/OpenCC, and
// <version> is the release it was taken from, such as ver.1.4.2. Run this again for a new
// release, and commit the file it writes.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT = 'shared/src/han-variants.ts';
const PAIRS_PER_LINE = 8;

// One character of the basic CJK block.
const inBlock = (text) => text.length === 1 && text >= '\u4e00' && text <= '\u9fff';
const escape = (char) => `\\u${char.charCodeAt(0).toString(16).padStart(4, '0')}`;

function pairsFrom(text) {
  const pairs = [];
  for (const line of text.split('\n')) {
    if (line.startsWith('#')) continue;
    // A line is a traditional character, a tab, and its simplified forms with spaces between.
    const [traditional, forms] = line.trim().split('\t');
    const simplified = forms?.split(' ')[0];
    if (!simplified || simplified === traditional) continue;
    if (inBlock(traditional) && inBlock(simplified)) pairs.push([traditional, simplified]);
  }
  // A simplified form may have a simpler form of its own. Follow it to the end, so that turning
  // a character into its simplified form once is enough.
  const forms = new Map(pairs);
  for (const pair of pairs) {
    const seen = new Set([pair[0]]);
    while (forms.has(pair[1]) && !seen.has(pair[1])) {
      seen.add(pair[1]);
      pair[1] = forms.get(pair[1]);
    }
  }
  return pairs.sort((a, b) => a[0].charCodeAt(0) - b[0].charCodeAt(0));
}

function main() {
  const [input, version] = process.argv.slice(2);
  if (!input || !version) {
    console.error('Usage: node scripts/build-han-variants.mjs path/to/TSCharacters.txt <version>');
    process.exit(2);
  }
  const pairs = pairsFrom(readFileSync(input, 'utf8'));
  if (pairs.length < 2000) {
    console.error(`${input} doesn't look like OpenCC's TSCharacters.txt.`);
    process.exit(1);
  }

  const lines = [];
  for (let i = 0; i < pairs.length; i += PAIRS_PER_LINE) {
    const chunk = pairs.slice(i, i + PAIRS_PER_LINE);
    lines.push(`  '${chunk.map(([traditional, simplified]) => escape(traditional) + escape(simplified)).join('')}'`);
  }
  const source = `// Generated by scripts/build-han-variants.mjs from TSCharacters.txt of OpenCC ${version}. Don't
// edit it by hand: run the script again.
//
// ${pairs.length} traditional Chinese characters, each followed by its simplified form.
//
// The data comes from the Open Chinese Convert project, https://github.com/BYVoid/OpenCC, and
// is used under the Apache License 2.0: https://www.apache.org/licenses/LICENSE-2.0. It was
// changed for this file: only the characters of the basic CJK block are kept, each with the
// first of its simplified forms.

// prettier-ignore
export const HAN_VARIANTS =
${lines.join(' +\n')};
`;
  writeFileSync(join(root, OUTPUT), source);
  console.log(`build-han-variants: wrote ${pairs.length} pairs to ${OUTPUT} (OpenCC ${version})`);
}

main();
