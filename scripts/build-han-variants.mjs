#!/usr/bin/env node
// Builds shared/src/han-variants.ts: the table that turns traditional Chinese characters into
// simplified ones, so that the clue check sees a word and its traditional spelling as the same
// word (shared/src/games/keywords/clue.ts).
//
// The table comes from the kSimplifiedVariant field of the Unicode Han Database (Unihan). It
// holds every character of the basic CJK block, U+4E00 to U+9FFF, that Unihan gives another
// character of that block as its simplified form. Where Unihan lists several forms, the first
// one counts, and a form that has a simpler form of its own is followed to the end. The
// characters are written as \u escapes, like all Chinese text in the code
// (docs/rules/language.md).
//
// Usage:
//   node scripts/build-han-variants.mjs path/to/Unihan_Variants.txt
//
// Unihan_Variants.txt is in https://www.unicode.org/Public/UCD/latest/ucd/Unihan.zip. Run this
// again for a new Unicode version, and commit the file it writes.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT = 'shared/src/han-variants.ts';
const PAIRS_PER_LINE = 8;

const inBlock = (codePoint) => codePoint >= 0x4e00 && codePoint <= 0x9fff;
const escape = (codePoint) => `\\u${codePoint.toString(16).padStart(4, '0')}`;

function pairsFrom(text) {
  const pairs = [];
  for (const line of text.split('\n')) {
    const [source, field, forms] = line.split('\t');
    if (field !== 'kSimplifiedVariant' || !forms) continue;
    const traditional = parseInt(source.slice(2), 16);
    // A form looks like U+5E72, sometimes followed by where it comes from, as in U+5E72<kFenn.
    const simplified = forms
      .split(' ')
      .map((form) => parseInt(form.slice(2), 16))
      .find((form) => form !== traditional && inBlock(form));
    if (inBlock(traditional) && simplified !== undefined) pairs.push([traditional, simplified]);
  }
  // A simplified form may have a simpler form of its own. Follow it to the end, so that turning
  // a character into its simplified form once is enough.
  const forms = new Map(pairs);
  for (const pair of pairs) {
    const seen = new Set([pair[0]]);
    while (forms.has(pair[1]) && !seen.has(pair[1])) {
      seen.add(pair[1]);
      pair[1] = forms.get(pair[1]);
    }
  }
  return pairs.sort((a, b) => a[0] - b[0]);
}

function main() {
  const [input] = process.argv.slice(2);
  if (!input) {
    console.error('Usage: node scripts/build-han-variants.mjs path/to/Unihan_Variants.txt');
    process.exit(2);
  }
  const text = readFileSync(input, 'utf8');
  const version = /^# Unicode Version (\S+)/m.exec(text)?.[1];
  const pairs = pairsFrom(text);
  if (!version || pairs.length < 2000) {
    console.error(`${input} doesn't look like Unihan_Variants.txt.`);
    process.exit(1);
  }

  const lines = [];
  for (let i = 0; i < pairs.length; i += PAIRS_PER_LINE) {
    const chunk = pairs.slice(i, i + PAIRS_PER_LINE);
    lines.push(`  '${chunk.map(([traditional, simplified]) => escape(traditional) + escape(simplified)).join('')}'`);
  }
  const source = `// Generated by scripts/build-han-variants.mjs from Unihan_Variants.txt, Unicode ${version}. Don't
// edit it by hand: run the script again.
//
// ${pairs.length} traditional Chinese characters, each followed by its simplified form.
//
// The data comes from the Unicode Character Database, (c) Unicode, Inc., and is used under the
// Unicode License v3: https://www.unicode.org/license.txt

// prettier-ignore
export const HAN_VARIANTS =
${lines.join(' +\n')};
`;
  writeFileSync(join(root, OUTPUT), source);
  console.log(`build-han-variants: wrote ${pairs.length} pairs to ${OUTPUT} (Unicode ${version})`);
}

main();
